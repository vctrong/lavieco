// Regenerates the logo embedded (cid:) in every email from the brand logo of the web
// app: 360 px wide (2× the 180 px it is shown at), flattened on white so it never sinks
// into a dark email background. Run after the brand logo changes:
//
//   node infra/scripts/email-logo.mjs
import { writeFileSync } from "node:fs";
import sharp from "sharp";

const SOURCE = "apps/web/public/images/brand/logo.png";
const TARGET = "packages/service-kit/src/notify/email/email-logo.ts";
const WIDTH = 360;

const { data, info } = await sharp(SOURCE)
  .resize({ width: WIDTH })
  .flatten({ background: "#ffffff" })
  .png({ compressionLevel: 9, palette: true })
  .toBuffer({ resolveWithObject: true });

writeFileSync(
  TARGET,
  [
    "// Generated by infra/scripts/email-logo.mjs from the brand logo. Do not edit by hand.",
    `export const EMAIL_LOGO = {`,
    `  width: ${info.width / 2},`,
    `  height: ${Math.round(info.height / 2)},`,
    `  base64:`,
    `    "${data.toString("base64")}",`,
    `} as const;`,
    "",
  ].join("\n"),
);
process.stdout.write(`${TARGET}: ${info.width}x${info.height}, ${data.length} bytes\n`);
